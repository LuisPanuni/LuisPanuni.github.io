function resizeNetwork() {
  const bounds = networkCanvas.getBoundingClientRect();
  if (!bounds.width || !bounds.height) return;
  const pixelRatio = Math.min(window.devicePixelRatio || 1, 2);
  networkCanvas.width = Math.round(bounds.width * pixelRatio);
  networkCanvas.height = Math.round(bounds.height * pixelRatio);
  networkContext.setTransform(pixelRatio, 0, 0, pixelRatio, 0, 0);
  networkWidth = bounds.width;
  networkHeight = bounds.height;
  const pointCount = Math.min(50, Math.max(20, Math.round(networkWidth / 11)));
  plasmaParticles = Array.from({ length: 180 }, () => ({ x: Math.random() * 2 - 1, y: Math.random() * 2 - 1, drift: .15 + Math.random() * .65, size: .7 + Math.random() * 1.6, phase: Math.random() * Math.PI * 2 }));
  networkPoints = Array.from({ length: pointCount }, () => ({
    x: Math.random() * networkWidth,
    y: Math.random() * networkHeight,
    vx: (Math.random() - .5) * .18,
    vy: (Math.random() - .5) * .18,
    pulse: Math.random() * Math.PI * 2
  }));
  // Paint a frame immediately, then start motion on the next browser frame.
  // Previously resize only painted a static frame; animation waited until a
  // later resize/visibility event happened to schedule requestAnimationFrame.
  drawNetwork(performance.now(), true);
  cancelAnimationFrame(networkFrameId);
  if (!networkMotionPreference.matches && !document.hidden) {
    networkFrameId = requestAnimationFrame(drawNetwork);
  }
}

function drawNetwork(time, staticFrame = false) {
  if (!networkWidth || !networkHeight) return;
  if (!staticFrame && time - lastNetworkFrame < 32) {
    networkFrameId = requestAnimationFrame(drawNetwork);
    return;
  }
  lastNetworkFrame = time;
  const context = networkContext;
  const accent = getComputedStyle(document.documentElement).getPropertyValue("--blue").trim() || "#7896b7";
  context.clearRect(0, 0, networkWidth, networkHeight);

  if (!networkMotionPreference.matches && !staticFrame) {
    for (const point of networkPoints) {
      point.x += point.vx;
      point.y += point.vy;
      if (point.x < 0 || point.x > networkWidth) point.vx *= -1;
      if (point.y < 0 || point.y > networkHeight) point.vy *= -1;
      point.x = Math.max(0, Math.min(networkWidth, point.x));
      point.y = Math.max(0, Math.min(networkHeight, point.y));
    }
  }

  const orbX = networkWidth * .5;
  const orbY = networkHeight * .52;
  const orbRadius = Math.min(networkHeight * .28, networkWidth * .17);
  const orbGlow = context.createRadialGradient(orbX, orbY, orbRadius * .08, orbX, orbY, orbRadius * 1.12);
  orbGlow.addColorStop(0, "rgba(73, 112, 150, .3)");
  orbGlow.addColorStop(.62, "rgba(47, 76, 108, .2)");
  orbGlow.addColorStop(1, "rgba(47, 76, 108, 0)");
  context.fillStyle = orbGlow;
  context.beginPath(); context.arc(orbX, orbY, orbRadius * 1.12, 0, Math.PI * 2); context.fill();
  context.save();
  context.beginPath(); context.arc(orbX, orbY, orbRadius, 0, Math.PI * 2); context.clip();
  const orbFill = context.createRadialGradient(orbX - orbRadius * .35, orbY - orbRadius * .4, orbRadius * .03, orbX, orbY, orbRadius);
  orbFill.addColorStop(0, "rgba(86, 132, 171, .26)"); orbFill.addColorStop(.56, "rgba(48, 79, 111, .16)"); orbFill.addColorStop(1, "rgba(11, 20, 33, .08)");
  context.fillStyle = orbFill; context.fillRect(orbX-orbRadius, orbY-orbRadius, orbRadius*2, orbRadius*2);
  for (let strand = 0; strand < 6; strand += 1) {
    const phase = time * .00036 + strand * Math.PI / 3;
    context.beginPath();
    for (let step = 0; step <= 36; step += 1) {
      const t = step / 36;
      const x = orbX + Math.sin(t * Math.PI * 2 + phase) * orbRadius * (.25 + t * .56);
      const y = orbY + (t - .5) * orbRadius * 1.75;
      if (step === 0) context.moveTo(x, y); else context.lineTo(x, y);
    }
    context.strokeStyle = strand % 2 ? "rgba(120, 155, 188, .27)" : "rgba(155, 181, 205, .34)"; context.lineWidth = .9; context.stroke();
  }
  for (const particle of plasmaParticles) {
    const drift = networkMotionPreference.matches || staticFrame ? 0 : time * .00006 * particle.drift;
    const px = particle.x * orbRadius * .92 + Math.sin(time * .0005 + particle.phase) * 5;
    const py = ((((particle.y + drift + 1) % 2) + 2) % 2 - 1) * orbRadius * .92;
    if (px * px + py * py > orbRadius * orbRadius) continue;
    context.globalAlpha = .2 + (Math.sin(time * .002 + particle.phase) + 1) * .16;
    context.fillStyle = particle.size > 1.6 ? "#a8bfd4" : accent;
    context.fillRect(orbX + px, orbY + py, particle.size, particle.size);
  }
  context.globalAlpha = 1;
  context.restore();
  context.beginPath(); context.arc(orbX, orbY, orbRadius, 0, Math.PI * 2);
  context.strokeStyle = "rgba(120, 155, 188, .4)"; context.lineWidth = 1; context.stroke();

  for (let i = 0; i < networkPoints.length; i += 1) {
    const first = networkPoints[i];
    for (let j = i + 1; j < networkPoints.length; j += 1) {
      const second = networkPoints[j];
      const dx = second.x - first.x;
      const dy = second.y - first.y;
      const distance = Math.hypot(dx, dy);
      if (distance < 112) {
        context.beginPath();
        context.moveTo(first.x, first.y);
        context.lineTo(second.x, second.y);
        context.strokeStyle = accent;
        context.globalAlpha = (1 - distance / 112) * .11;
        context.lineWidth = .75;
        context.stroke();
      }
    }
    if (networkPointer.active) {
      const dx = networkPointer.x - first.x;
      const dy = networkPointer.y - first.y;
      const distance = Math.hypot(dx, dy);
      if (distance < 126) {
        context.beginPath();
        context.moveTo(first.x, first.y);
        context.lineTo(networkPointer.x, networkPointer.y);
        context.strokeStyle = accent;
        context.globalAlpha = (1 - distance / 126) * .24;
        context.lineWidth = .9;
        context.stroke();
      }
    }
    const radius = networkPointer.active && Math.hypot(networkPointer.x - first.x, networkPointer.y - first.y) < 126 ? 1.8 : 1.1;
    context.beginPath();
    context.arc(first.x, first.y, radius, 0, Math.PI * 2);
    context.fillStyle = accent;
    context.globalAlpha = radius > 1.2 ? .56 : .3;
    context.fill();
  }
  context.globalAlpha = 1;

  if (!staticFrame && !networkMotionPreference.matches && !document.hidden) networkFrameId = requestAnimationFrame(drawNetwork);
}

window.addEventListener("pointermove", (event) => {
  networkPointer.x = event.clientX;
  networkPointer.y = event.clientY;
  networkPointer.active = true;
});
window.addEventListener("pointerout", (event) => { if (!event.relatedTarget) networkPointer.active = false; });
window.addEventListener("resize", resizeNetwork, { passive: true });
document.addEventListener("visibilitychange", () => {
  if (document.hidden) cancelAnimationFrame(networkFrameId);
  else networkFrameId = requestAnimationFrame(drawNetwork);
});
networkMotionPreference.addEventListener?.("change", () => {
  cancelAnimationFrame(networkFrameId);
  if (networkMotionPreference.matches) drawNetwork(0, true);
  else networkFrameId = requestAnimationFrame(drawNetwork);
});
resizeNetwork();
